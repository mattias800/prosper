// test_audiodec — libSceAudiodec's guest-facing contract, end to end through the FFmpeg AAC backend.
//
// The defect this pins is a boot-killer, not a cosmetic one. Every entry point in this library used
// to be unregistered, so the dispatcher answered `0` — SCE_OK for a status-returning contract — and
// wrote nothing. *The Lord of the Rings: Gollum* (PPSA06367) then read the stream's channel count
// out of a bitstream-info block nothing had filled and divided by it:
//
//     eboot+0xec15f6   add rsi,rsi      ; 2 bytes per sample * uiChannels
//     eboot+0xec15f9   div rsi          ; uiChannels == 0  ->  #DE  ->  the process dies
//
// So the assertion that matters is not "decode returned 0"; it is **the guest's own divisor is
// non-zero on every call that reported success**. That arithmetic is reproduced literally below.
#include "hle/dispatch/dispatch.hpp"
#include "hle/dispatch/nid.hpp"
#include "hle/audio/ajm_decoder.hpp"
#include "ajm_ffmpeg.hpp"

#include <cstdint>
#include <cstdio>
#include <cstring>
#include <vector>

using namespace prosper;

static int fails = 0;
#define CHECK(c, m) do { if (!(c)) { std::printf("  [FAIL] %s\n", m); ++fails; } \
                         else       { std::printf("  [ok]   %s\n", m); } } while (0)

using HleFn = uint64_t (*)(uint64_t, uint64_t, uint64_t, uint64_t, uint64_t, uint64_t);
static uint64_t addr(const void* p) { return (uint64_t)(uintptr_t)p; }
static bool is_error(uint64_t r) { return (int32_t)(uint32_t)r < 0; }

