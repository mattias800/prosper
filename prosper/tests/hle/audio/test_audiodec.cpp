static const unsigned int kAacUnitSizes[] = {188, 259, 216, 245};

// The guest structures, exactly as recovered from PPSA06367's call sites (see hle_audiodec.cpp).
#pragma pack(push, 1)
struct Ctrl     { uint64_t param, bsi_info, au_info, pcm_item; };
struct AuInfo   { uint32_t size, rsv; uint64_t addr; uint32_t au_size, rsv2; };
struct PcmItem  { uint32_t size, rsv; uint64_t addr; uint32_t pcm_size, rsv2; };
struct BsiInfo  { uint32_t size, sample_rate, channels, rsv[2]; };
struct ParamAac { uint32_t size, version, object_type, rate_index, channel_config, flag,
                  enable, rsv; };
#pragma pack(pop)
static_assert(sizeof(Ctrl) == 0x20);
static_assert(sizeof(AuInfo) == 0x18);
static_assert(sizeof(PcmItem) == 0x18);
static_assert(sizeof(BsiInfo) == 0x14);
static_assert(sizeof(ParamAac) == 0x20);

// One decoder's worth of guest-shaped memory, wired the way Electra wires it.
struct Fixture {
    ParamAac param{};
    BsiInfo bsi{};
    AuInfo au{};
    PcmItem pcm{};
    Ctrl ctrl{};
    std::vector<int16_t> pcm_buffer;

    // `object_type == 0` reproduces a caller that supplies no AudioSpecificConfig at all.
    explicit Fixture(uint32_t object_type = 2, uint32_t rate_index = 3, uint32_t channel_config = 2)
        : pcm_buffer(16384 / sizeof(int16_t), 0) {
        param.size = 0x20;
        param.version = 1;
        param.object_type = object_type;
        param.rate_index = rate_index;
        param.channel_config = channel_config;
        param.enable = 1;
        bsi.size = 0x14;
        au.size = 0x18;
        pcm.size = 0x18;
        pcm.addr = addr(pcm_buffer.data());
        pcm.pcm_size = (uint32_t)(pcm_buffer.size() * sizeof(int16_t));
        ctrl = {addr(&param), addr(&bsi), addr(&au), addr(&pcm)};
    }

    void submit(const unsigned char* unit, uint32_t size) {
        au.addr = addr(unit);
        au.au_size = size;
        pcm.pcm_size = (uint32_t)(pcm_buffer.size() * sizeof(int16_t));  // capacity, in again
    }
};

int main() {
    std::printf("test_audiodec\n");

    CHECK(ajm::install_ffmpeg_decoder_backend(), "FFmpeg decoder backend installs");
    register_audiodec_hle();

    // --- the published MPEG-4 index table -------------------------------------------------------
    CHECK(ajm::aac_sample_rate_from_index(3) == 48000, "ASC index 3 is 48000 Hz");
    CHECK(ajm::aac_sample_rate_from_index(4) == 44100, "ASC index 4 is 44100 Hz");
    CHECK(ajm::aac_sample_rate_from_index(0) == 96000, "ASC index 0 is 96000 Hz");
    CHECK(ajm::aac_sample_rate_from_index(13) == 0, "ASC index 13 is not a defined rate");
    CHECK(ajm::aac_sample_rate_from_index(15) == 0, "ASC index 15 (explicit rate) is refused");

    // --- registration -------------------------------------------------------------------------
    // The whole defect was that these resolved to nothing and the dispatcher answered SCE_OK, so a
    // null lookup here IS the bug reappearing.
    auto init_library   = (HleFn)Hle::lookup(nid_hash("sceAudiodecInitLibrary"));
    auto create_decoder = (HleFn)Hle::lookup(nid_hash("sceAudiodecCreateDecoder"));
    auto decode         = (HleFn)Hle::lookup(nid_hash("sceAudiodecDecode"));
    auto delete_decoder = (HleFn)Hle::lookup(nid_hash("sceAudiodecDeleteDecoder"));
    auto clear_context  = (HleFn)Hle::lookup(nid_hash("sceAudiodecClearContext"));
    auto term_library   = (HleFn)Hle::lookup(nid_hash("sceAudiodecTermLibrary"));
    CHECK(init_library && create_decoder && decode && delete_decoder && clear_context &&
          term_library, "every libSceAudiodec entry point is registered");
    if (!init_library || !create_decoder || !decode || !delete_decoder || !clear_context ||
        !term_library) {
        std::printf("test_audiodec: %d failure(s)\n", fails + 1);
        return 1;
    }

    CHECK(init_library(3, 0, 0, 0, 0, 0) == 0, "sceAudiodecInitLibrary(AAC) succeeds");
    CHECK(is_error(init_library(1, 0, 0, 0, 0, 0)),
          "sceAudiodecInitLibrary refuses a codec type it cannot serve");

    // --- the live shape: PPSA06367's own parameter block ----------------------------------------
    {
        Fixture f;
        const uint64_t handle = create_decoder(addr(&f.ctrl), 3, 0, 0, 0, 0);
        CHECK(!is_error(handle), "sceAudiodecCreateDecoder returns a non-negative handle");
        // CreateDecoder must publish the configured shape immediately: a decode that produces no
        // PCM yet must not leave the guest's divisor at zero.
        CHECK(f.bsi.sample_rate == 48000 && f.bsi.channels == 2,
              "CreateDecoder publishes the configured 48 kHz / 2 ch to pBsiInfo");

        uint32_t total_pcm = 0, decoded_units = 0;
        for (unsigned i = 0; i < sizeof(kAacUnitSizes) / sizeof(kAacUnitSizes[0]); ++i) {
            f.submit(kAacUnits[i], kAacUnitSizes[i]);
            const uint64_t rc = decode(handle, addr(&f.ctrl), 0, 0, 0, 0);
            CHECK(rc == 0, "sceAudiodecDecode accepts a raw AAC access unit");
            if (rc != 0) break;
            CHECK(f.au.au_size == kAacUnitSizes[i],
                  "uiAuSize reports the whole access unit as consumed");
            // eboot+0xec15f9, reproduced: the guest divides by this. A zero here is the crash.
            CHECK(f.bsi.channels != 0, "pBsiInfo->uiChannels is non-zero (the guest divides by it)");
            if (f.bsi.channels == 0) break;
            const uint32_t frames = f.pcm.pcm_size / (2 * f.bsi.channels);
            CHECK(f.bsi.sample_rate == 48000 && f.bsi.channels == 2,
                  "pBsiInfo reports what actually decoded: 48 kHz stereo");
            (void)frames;
            total_pcm += f.pcm.pcm_size;
            ++decoded_units;
        }
        CHECK(decoded_units == sizeof(kAacUnitSizes) / sizeof(kAacUnitSizes[0]),
              "every fixture access unit decoded");
        // One AAC-LC frame is 1024 samples; stereo S16 makes 4096 bytes. The decoder primes on the
        // first unit, so the run produces at least one frame fewer than it consumed.
        CHECK(total_pcm >= 4096, "the run produced real interleaved S16 PCM");

        CHECK(clear_context(handle, 0, 0, 0, 0, 0) == 0, "sceAudiodecClearContext succeeds");
        CHECK(delete_decoder(handle, 0, 0, 0, 0, 0) == 0, "sceAudiodecDeleteDecoder succeeds");
        CHECK(is_error(delete_decoder(handle, 0, 0, 0, 0, 0)),
              "deleting the same handle twice is refused");
        CHECK(is_error(decode(handle, addr(&f.ctrl), 0, 0, 0, 0)),
              "decoding on a deleted handle is refused");
    }

    // --- the AudioSpecificConfig is load-bearing, not decoration --------------------------------
    // A raw AAC elementary stream carries no in-band configuration. With the guest's ASC fields
    // withheld, the same bytes must NOT decode -- otherwise the arm above would pass for a reason
    // that has nothing to do with reconstructing the config, and this whole path would be untested.
    {
        Fixture f(/*object_type=*/0);
        const uint64_t handle = create_decoder(addr(&f.ctrl), 3, 0, 0, 0, 0);
        bool any_ok = false;
        if (!is_error(handle)) {
            for (unsigned i = 0; i < sizeof(kAacUnitSizes) / sizeof(kAacUnitSizes[0]); ++i) {
                f.submit(kAacUnits[i], kAacUnitSizes[i]);
                if (decode(handle, addr(&f.ctrl), 0, 0, 0, 0) == 0 && f.pcm.pcm_size > 0)
                    any_ok = true;
            }
            delete_decoder(handle, 0, 0, 0, 0, 0);
        }
        CHECK(!any_ok, "without the guest's AudioSpecificConfig the same units do NOT decode");
    }

    // --- refusals, all of which must be negative rather than a handle ---------------------------
    {
        Fixture f(2, /*rate_index=*/13, 2);   // 13 is not a defined sampling-frequency index
        CHECK(is_error(create_decoder(addr(&f.ctrl), 3, 0, 0, 0, 0)),
              "an undefined sampling-frequency index is refused");
    }
    {
        Fixture f;
        f.param.size = 0x10;                  // shorter than the AAC parameter block
        CHECK(is_error(create_decoder(addr(&f.ctrl), 3, 0, 0, 0, 0)),
              "a parameter block declaring too small a uiSize is refused");
    }
    {
        Fixture f;
        f.param.channel_config = 0;           // "described by a program config element"
        CHECK(is_error(create_decoder(addr(&f.ctrl), 3, 0, 0, 0, 0)),
              "channel configuration 0 is refused rather than decoded as silence");
    }
    {
        Fixture f;
        CHECK(is_error(create_decoder(addr(&f.ctrl), /*codecType=*/7, 0, 0, 0, 0)),
              "an unimplemented codec type is refused");
    }
    CHECK(is_error(create_decoder(0, 3, 0, 0, 0, 0)),
          "a null control block is refused rather than dereferenced");

    CHECK(term_library(3, 0, 0, 0, 0, 0) == 0, "sceAudiodecTermLibrary succeeds");

    std::printf("test_audiodec: %d failure(s)\n", fails);
    return fails ? 1 : 0;
}
